"""
Code Quality Metrics for Sprint 4

Implements four metrics for evaluating agent performance on coding tasks:
1. Task Completion Rate - Did the task complete successfully?
2. Specification Adherence - Does the code match requirements?
3. Code Quality - Is the code well-written and maintainable?
4. Token Efficiency - How efficient is token usage per correct line?
"""

import ast
import re
from abc import ABC, abstractmethod
from typing import Dict, Any, List, Optional
from dataclasses import dataclass


@dataclass
class MetricResult:
    """Result from a metric calculation."""
    score: float  # Normalized 0.0-1.0
    raw_value: Any  # Raw metric value
    details: Dict[str, Any]  # Additional details


class BaseMetric(ABC):
    """Base class for all evaluation metrics."""

    @abstractmethod
    def calculate(self, generated_code: str, task_data: Dict[str, Any]) -> MetricResult:
        """
        Calculate metric score for generated code.

        Args:
            generated_code: Code generated by agent
            task_data: Task metadata and test results

        Returns:
            MetricResult with score (0.0-1.0) and details
        """
        pass

    @abstractmethod
    def get_name(self) -> str:
        """Return metric name."""
        pass

    @abstractmethod
    def get_description(self) -> str:
        """Return metric description."""
        pass

    def normalize_score(self, raw_value: float, min_val: float, max_val: float) -> float:
        """
        Normalize raw value to 0.0-1.0 range.

        Args:
            raw_value: Raw metric value
            min_val: Minimum possible value
            max_val: Maximum possible value

        Returns:
            Normalized score in [0.0, 1.0]
        """
        if max_val == min_val:
            return 1.0 if raw_value >= max_val else 0.0
        return max(0.0, min(1.0, (raw_value - min_val) / (max_val - min_val)))


class TaskCompletionRateMetric(BaseMetric):
    """
    Metric 1: Task Completion Rate

    Measures whether the task completed successfully:
    - 1.0: All tests passed, no errors
    - 0.5: Code runs but some tests failed
    - 0.0: Code doesn't run (syntax errors, crashes)
    """

    def get_name(self) -> str:
        return "Task Completion Rate"

    def get_description(self) -> str:
        return "Measures successful task completion (tests passing, no errors)"

    def calculate(self, generated_code: str, task_data: Dict[str, Any]) -> MetricResult:
        """
        Calculate completion rate.

        Score:
        - 1.0: All tests passed
        - 0.5-0.9: Some tests passed (proportional)
        - 0.3: Code runs but no tests passed
        - 0.0: Syntax error or runtime crash
        """
        details = {}

        # Check syntax validity
        is_valid_syntax = self._check_syntax(generated_code)
        details['syntax_valid'] = is_valid_syntax

        if not is_valid_syntax:
            return MetricResult(
                score=0.0,
                raw_value={'tests_passed': 0, 'tests_total': 0, 'syntax_valid': False},
                details=details
            )

        # Get test results
        test_results = task_data.get('test_results', {})
        tests_passed = test_results.get('passed', 0)
        tests_total = test_results.get('total', 0)
        all_passed = test_results.get('all_passed', False)

        details['tests_passed'] = tests_passed
        details['tests_total'] = tests_total

        # Calculate score
        if all_passed and tests_total > 0:
            score = 1.0
        elif tests_total > 0:
            # Partial credit: 0.5 + (0.4 * pass_rate)
            pass_rate = tests_passed / tests_total
            score = 0.5 + (0.4 * pass_rate)
        else:
            # Code runs but no tests (or no tests to run)
            score = 0.3

        return MetricResult(
            score=score,
            raw_value={'tests_passed': tests_passed, 'tests_total': tests_total, 'syntax_valid': True},
            details=details
        )

    def _check_syntax(self, code: str) -> bool:
        """Check if code has valid Python syntax."""
        try:
            ast.parse(code)
            return True
        except SyntaxError:
            return False


class SpecificationAdherenceMetric(BaseMetric):
    """
    Metric 2: Specification Adherence

    Measures how well the code matches requirements:
    - Required functions/classes implemented?
    - Correct signatures?
    - Expected behavior implemented?
    """

    def get_name(self) -> str:
        return "Specification Adherence"

    def get_description(self) -> str:
        return "Measures how well code matches task requirements"

    def calculate(self, generated_code: str, task_data: Dict[str, Any]) -> MetricResult:
        """
        Calculate specification adherence.

        Checks:
        1. Required entities present (functions, classes)
        2. Correct signatures
        3. Implementation completeness
        """
        details = {}

        # Parse code to get definitions
        try:
            tree = ast.parse(generated_code)
            definitions = self._extract_definitions(tree)
            details['definitions_found'] = definitions
        except SyntaxError:
            return MetricResult(
                score=0.0,
                raw_value={'syntax_valid': False},
                details=details
            )

        # Get requirements from task
        requirements = task_data.get('requirements', {})
        required_functions = requirements.get('functions', [])
        required_classes = requirements.get('classes', [])

        # Check function presence
        function_score = self._check_entities(
            definitions.get('functions', []),
            required_functions,
            details
        )

        # Check class presence
        class_score = self._check_entities(
            definitions.get('classes', []),
            required_classes,
            details
        )

        # Combine scores (weighted average)
        total_required = len(required_functions) + len(required_classes)
        if total_required == 0:
            # No specific requirements, use test results as proxy
            test_results = task_data.get('test_results', {})
            if test_results.get('all_passed', False):
                score = 1.0
            else:
                score = 0.5
        else:
            weight_func = len(required_functions) / total_required if total_required > 0 else 0.5
            weight_class = len(required_classes) / total_required if total_required > 0 else 0.5
            score = (function_score * weight_func) + (class_score * weight_class)

        return MetricResult(
            score=score,
            raw_value={'function_score': function_score, 'class_score': class_score},
            details=details
        )

    def _extract_definitions(self, tree: ast.AST) -> Dict[str, List[str]]:
        """Extract function and class definitions from AST."""
        functions = []
        classes = []

        for node in ast.walk(tree):
            if isinstance(node, ast.FunctionDef):
                functions.append(node.name)
            elif isinstance(node, ast.ClassDef):
                classes.append(node.name)

        return {'functions': functions, 'classes': classes}

    def _check_entities(self, found: List[str], required: List[str], details: Dict) -> float:
        """Check if required entities are present."""
        if not required:
            return 1.0

        found_set = set(found)
        required_set = set(required)
        matched = found_set.intersection(required_set)

        details[f'required_{len(required)}'] = list(required_set)
        details[f'matched_{len(matched)}'] = list(matched)

        return len(matched) / len(required) if required else 1.0


class CodeQualityMetric(BaseMetric):
    """
    Metric 3: Code Quality

    Measures code quality using multiple factors:
    - Cyclomatic complexity (lower is better)
    - Code structure (proper functions, classes)
    - Documentation (docstrings present)
    - Maintainability (line length, nesting depth)
    """

    def get_name(self) -> str:
        return "Code Quality"

    def get_description(self) -> str:
        return "Measures code quality (complexity, structure, documentation)"

    def calculate(self, generated_code: str, task_data: Dict[str, Any]) -> MetricResult:
        """
        Calculate code quality score.

        Factors (weighted):
        - Complexity: 30%
        - Structure: 25%
        - Documentation: 25%
        - Maintainability: 20%
        """
        details = {}

        # Parse code
        try:
            tree = ast.parse(generated_code)
        except SyntaxError:
            return MetricResult(
                score=0.0,
                raw_value={'syntax_valid': False},
                details=details
            )

        # 1. Complexity (30%) - Cyclomatic complexity per function
        complexity_score = self._calculate_complexity_score(tree, details)

        # 2. Structure (25%) - Proper use of functions/classes
        structure_score = self._calculate_structure_score(tree, generated_code, details)

        # 3. Documentation (25%) - Docstrings present
        doc_score = self._calculate_documentation_score(tree, details)

        # 4. Maintainability (20%) - Line length, nesting
        maintainability_score = self._calculate_maintainability_score(generated_code, details)

        # Weighted average
        score = (
            complexity_score * 0.30 +
            structure_score * 0.25 +
            doc_score * 0.25 +
            maintainability_score * 0.20
        )

        return MetricResult(
            score=score,
            raw_value={
                'complexity': complexity_score,
                'structure': structure_score,
                'documentation': doc_score,
                'maintainability': maintainability_score
            },
            details=details
        )

    def _calculate_complexity_score(self, tree: ast.AST, details: Dict) -> float:
        """Calculate complexity score (simpler is better)."""
        complexities = []

        for node in ast.walk(tree):
            if isinstance(node, ast.FunctionDef):
                complexity = self._cyclomatic_complexity(node)
                complexities.append(complexity)

        if not complexities:
            avg_complexity = 1
        else:
            avg_complexity = sum(complexities) / len(complexities)

        details['avg_complexity'] = avg_complexity
        details['num_functions'] = len(complexities)

        # Score: 1.0 for complexity <= 5, decreasing for higher
        if avg_complexity <= 5:
            return 1.0
        elif avg_complexity <= 10:
            return 0.7
        elif avg_complexity <= 15:
            return 0.4
        else:
            return 0.2

    def _cyclomatic_complexity(self, node: ast.FunctionDef) -> int:
        """Calculate cyclomatic complexity of a function."""
        complexity = 1  # Base complexity

        for child in ast.walk(node):
            # Add 1 for each branch point
            if isinstance(child, (ast.If, ast.While, ast.For, ast.ExceptHandler)):
                complexity += 1
            elif isinstance(child, ast.BoolOp):
                complexity += len(child.values) - 1

        return complexity

    def _calculate_structure_score(self, tree: ast.AST, code: str, details: Dict) -> float:
        """Calculate structure score (proper organization)."""
        num_functions = 0
        num_classes = 0

        for node in ast.walk(tree):
            if isinstance(node, ast.FunctionDef):
                num_functions += 1
            elif isinstance(node, ast.ClassDef):
                num_classes += 1

        lines = code.split('\n')
        code_lines = [l for l in lines if l.strip() and not l.strip().startswith('#')]

        details['num_functions'] = num_functions
        details['num_classes'] = num_classes
        details['code_lines'] = len(code_lines)

        # Good structure: code organized into functions/classes
        if len(code_lines) == 0:
            return 0.0

        # Ratio of organized code (functions + classes)
        total_entities = num_functions + num_classes
        if total_entities >= 3:
            return 1.0
        elif total_entities >= 2:
            return 0.8
        elif total_entities >= 1:
            return 0.6
        else:
            return 0.3  # All code at module level

    def _calculate_documentation_score(self, tree: ast.AST, details: Dict) -> float:
        """Calculate documentation score (docstrings present)."""
        functions_with_docs = 0
        total_functions = 0
        classes_with_docs = 0
        total_classes = 0

        for node in ast.walk(tree):
            if isinstance(node, ast.FunctionDef):
                total_functions += 1
                if ast.get_docstring(node):
                    functions_with_docs += 1
            elif isinstance(node, ast.ClassDef):
                total_classes += 1
                if ast.get_docstring(node):
                    classes_with_docs += 1

        details['functions_with_docs'] = functions_with_docs
        details['total_functions'] = total_functions
        details['classes_with_docs'] = classes_with_docs
        details['total_classes'] = total_classes

        # Calculate doc coverage
        total_entities = total_functions + total_classes
        if total_entities == 0:
            return 0.5  # No functions/classes to document

        documented = functions_with_docs + classes_with_docs
        coverage = documented / total_entities

        return coverage

    def _calculate_maintainability_score(self, code: str, details: Dict) -> float:
        """Calculate maintainability score (line length, nesting)."""
        lines = code.split('\n')

        # Check line lengths
        long_lines = sum(1 for line in lines if len(line) > 100)
        total_lines = len([l for l in lines if l.strip()])

        if total_lines == 0:
            return 0.0

        # Check nesting depth
        max_nesting = self._calculate_max_nesting(code)

        details['long_lines'] = long_lines
        details['total_lines'] = total_lines
        details['max_nesting'] = max_nesting

        # Score based on maintainability factors
        line_score = 1.0 - (long_lines / total_lines) if total_lines > 0 else 1.0
        nesting_score = 1.0 if max_nesting <= 3 else (0.5 if max_nesting <= 5 else 0.2)

        return (line_score + nesting_score) / 2

    def _calculate_max_nesting(self, code: str) -> int:
        """Calculate maximum nesting depth."""
        max_depth = 0
        current_depth = 0

        for line in code.split('\n'):
            stripped = line.lstrip()
            if not stripped or stripped.startswith('#'):
                continue

            # Calculate indentation
            indent = len(line) - len(stripped)
            depth = indent // 4  # Assuming 4-space indentation

            max_depth = max(max_depth, depth)

        return max_depth


class TokenEfficiencyMetric(BaseMetric):
    """
    Metric 4: Token Efficiency

    Measures token usage efficiency:
    - Tokens per correct line of code
    - Lower is better (less context needed for same output)
    """

    def get_name(self) -> str:
        return "Token Efficiency"

    def get_description(self) -> str:
        return "Measures token usage efficiency (tokens per correct line of code)"

    def calculate(self, generated_code: str, task_data: Dict[str, Any]) -> MetricResult:
        """
        Calculate token efficiency.

        Metric: Tokens per correct line of code
        - Lower is better
        - Normalized to 0.0-1.0 (inverted)
        """
        details = {}

        # Get token usage
        context_stats = task_data.get('context_stats', {})
        total_tokens = context_stats.get('total_tokens', 0)

        # Count lines of code
        lines = generated_code.split('\n')
        code_lines = [
            l for l in lines
            if l.strip() and not l.strip().startswith('#')
        ]
        num_code_lines = len(code_lines)

        # Check if code is correct (tests passed)
        test_results = task_data.get('test_results', {})
        all_passed = test_results.get('all_passed', False)

        details['total_tokens'] = total_tokens
        details['code_lines'] = num_code_lines
        details['tests_passed'] = all_passed

        if num_code_lines == 0 or total_tokens == 0:
            return MetricResult(
                score=0.0,
                raw_value={'tokens_per_line': float('inf')},
                details=details
            )

        # Calculate tokens per line
        tokens_per_line = total_tokens / num_code_lines
        details['tokens_per_line'] = tokens_per_line

        # Penalize if tests didn't pass
        if not all_passed:
            tokens_per_line *= 2  # Double the "cost" for incorrect code
            details['penalty_applied'] = True

        # Normalize to 0.0-1.0 (inverted - lower tokens is better)
        # Assume good efficiency is 100 tokens/line, poor is 1000+ tokens/line
        if tokens_per_line <= 100:
            score = 1.0
        elif tokens_per_line <= 300:
            score = 0.8
        elif tokens_per_line <= 500:
            score = 0.6
        elif tokens_per_line <= 800:
            score = 0.4
        elif tokens_per_line <= 1000:
            score = 0.2
        else:
            score = 0.1

        return MetricResult(
            score=score,
            raw_value={'tokens_per_line': tokens_per_line},
            details=details
        )


class MetricsCalculator:
    """
    Aggregates all metrics for a task result.
    """

    def __init__(self):
        self.metrics = [
            TaskCompletionRateMetric(),
            SpecificationAdherenceMetric(),
            CodeQualityMetric(),
            TokenEfficiencyMetric()
        ]

    def calculate_all(self, generated_code: str, task_data: Dict[str, Any]) -> Dict[str, MetricResult]:
        """
        Calculate all metrics for generated code.

        Args:
            generated_code: Code generated by agent
            task_data: Task metadata and test results

        Returns:
            Dictionary mapping metric name to MetricResult
        """
        results = {}

        for metric in self.metrics:
            result = metric.calculate(generated_code, task_data)
            results[metric.get_name()] = result

        return results

    def get_summary(self, metric_results: Dict[str, MetricResult]) -> Dict[str, float]:
        """
        Get summary scores for all metrics.

        Returns:
            Dictionary with metric names and scores
        """
        return {
            name: result.score
            for name, result in metric_results.items()
        }

    def get_aggregate_score(self, metric_results: Dict[str, MetricResult]) -> float:
        """
        Calculate aggregate score across all metrics.

        Weighted average:
        - Task Completion: 40%
        - Spec Adherence: 30%
        - Code Quality: 20%
        - Token Efficiency: 10%
        """
        weights = {
            'Task Completion Rate': 0.40,
            'Specification Adherence': 0.30,
            'Code Quality': 0.20,
            'Token Efficiency': 0.10
        }

        weighted_sum = 0.0
        for name, result in metric_results.items():
            weight = weights.get(name, 0.0)
            weighted_sum += result.score * weight

        return weighted_sum


